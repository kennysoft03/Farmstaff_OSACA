		<script type="text/javascript">
			(function($) {
				"use strict";

				$(function() {
					if (typeof $.fn.select2 !== 'function') {
						return;
					}

					$('select.form-control').each(function() {
						var $select = $(this);

						if (
							$select.hasClass('kt-select2') ||
							$select.hasClass('selectpicker') ||
							$select.hasClass('no-select2') ||
							$select.is('[data-no-select2]') ||
							$select.hasClass('select2-hidden-accessible')
						) {
							return;
						}

						var forceSearchable = $select.hasClass('kt-select2-auto') || String($select.data('searchable')) === '1';
						var optionCount = $select.find('option').length;
						if (!forceSearchable && optionCount < 8) {
							return;
						}

						var placeholder = $.trim($select.attr('data-placeholder') || $select.find('option:first').text() || 'Select a value');
						$select.select2({
							placeholder: placeholder,
							width: '100%',
							allowClear: !$select.prop('required')
						});
					});
				});
			})(jQuery);
		</script>